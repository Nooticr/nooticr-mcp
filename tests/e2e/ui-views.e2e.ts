async function boot(page: Page, tool = "") {
  const errs: string[] = [];
  page.on("pageerror", (e) => errs.push(String(e)));
  page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
  // Each tool is served at its own resource URI with its name baked in, which
  // is how the product view tells a create from a patch.
  await page.setContent(tool ? uiTemplateFor(tool) : NOOTICR_UI_TEMPLATE);
  return errs;
}
async function result(page: Page, d: unknown) {
  await page.evaluate((x) => window.postMessage({ method: "ui/notifications/tool-result", params: { structuredContent: x } }, "*"), d);
  await page.waitForTimeout(400);
}

