// ─── The wait, for every tool ───
// The vitest suite checks the plan data; these check the view's own evaluator,
// which is JavaScript inside a template string and cannot be imported.

async function loading(page: Page, name: string, args: Record<string, unknown>) {
  await page.evaluate(
    ([n, a]) => window.postMessage(
      { method: "ui/notifications/tool-input", params: { name: n, arguments: a } }, "*"),
    [name, args] as const,
  );
  await page.waitForTimeout(400);
}

test("the wait prices analyze_post at what it fans out to, not the direct rate", async ({ page }) => {
  const errs = await boot(page);
  await loading(page, "analyze_post", { url: "https://www.tiktok.com/@a/video/1" });
  // 3 = get_post_frames 2 + get_post_transcript 1. nooticr-server bills a
  // direct /mcp analyze_post at 6; this server never makes that call.
  expect(await page.locator(".load-price").textContent()).toBe("3 credits");
  const rows = page.locator(".led-row");
  expect(await rows.count()).toBe(2);
  expect(await rows.nth(0).locator(".led-label").textContent()).toBe("Sampling frames");
  expect(await rows.nth(1).locator(".led-cost").textContent()).toBe("1");
  expect(errs).toEqual([]);
});

test("an all-networks sweep itemises every network it will reach", async ({ page }) => {
  const errs = await boot(page);
  await loading(page, "search_mentions", { term: "nooticr" });
  // Omitting platforms means all nine, which is 21 — the number nothing the
  // caller read told them about.
  await expect(page.locator(".load-centre")).toBeVisible();
  expect(await page.locator(".load-what").textContent()).toBe(String.raw`Sweeping 9 networks for "nooticr"`);
  expect(await page.locator(".load-sub").textContent()).toContain("21 credits committed");
  expect(await page.locator(".led-row").count()).toBe(9);
  // Xiaohongshu costs more upstream, and the ledger says so per line.
  const xhs = page.locator(".led-row", { hasText: "Xiaohongshu" });
  expect(await xhs.locator(".led-cost").textContent()).toBe("5");
  expect(await page.locator(".led-foot").textContent()).toContain("ceiling, not a charge already taken");
  expect(errs).toEqual([]);
});

